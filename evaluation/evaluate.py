"""
Entity-level evaluation of the ResuMate hybrid parser (DistilBERT + rules).

    python evaluation/evaluate.py                       # model from the Hugging Face Hub
    python evaluation/evaluate.py --model path/to/dir   # local model

For every test resume and every field that the resume's ground truth annotates:

    TP  gold value matched by a prediction
    FN  gold value with no matching prediction
    FP  prediction that matches no gold value   <- not counted by the original script

Two matching modes are reported:

    exact    normalized strings are equal (case, whitespace, trailing punctuation ignored)
    lenient  the original project's rule: exact, or one string contains the other
             (both longer than 2 characters)

Fields a resume does not annotate are skipped entirely, so the model is never
penalised for predicting something the annotator did not label.

Writes evaluation/results/metrics.json and evaluation/results/report.md.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

DEFAULT_MODEL = "quicklearner404/DistillbertNER"
TEST_FILE = ROOT / "data" / "test" / "test_resumes.json"
RESULTS_DIR = Path(__file__).resolve().parent / "results"
LABELS = ["Name", "Email", "Company", "Designation", "Degree", "College", "Location", "Skills"]


def normalize(value: str) -> str:
    value = re.sub(r"\s+", " ", value.lower()).strip()
    return value.strip(" .,;:-")


def matches(pred: str, gold: str, mode: str) -> bool:
    if pred == gold:
        return True
    if mode == "lenient":
        return len(pred) > 2 and len(gold) > 2 and (pred in gold or gold in pred)
    return False


def score_field(preds: set[str], golds: set[str], mode: str) -> tuple[int, int, int, list, list]:
    """Return tp, fp, fn and the unmatched predictions / gold values."""
    matched_gold = {g for g in golds if any(matches(p, g, mode) for p in preds)}
    false_preds = sorted(p for p in preds if not any(matches(p, g, mode) for g in golds))
    missed = sorted(golds - matched_gold)
    return len(matched_gold), len(false_preds), len(missed), false_preds, missed


def prf(tp: int, fp: int, fn: int) -> dict:
    precision = tp / (tp + fp) if tp + fp else 0.0
    recall = tp / (tp + fn) if tp + fn else 0.0
    f1 = 2 * precision * recall / (precision + recall) if precision + recall else 0.0
    return {"precision": round(precision, 4), "recall": round(recall, 4), "f1": round(f1, 4),
            "tp": tp, "fp": fp, "fn": fn}


def evaluate(predictions: list[dict], test_data: list[dict], mode: str) -> dict:
    counts = defaultdict(lambda: [0, 0, 0])
    errors = []
    perfect = 0

    for i, (item, pred) in enumerate(zip(test_data, predictions, strict=True), start=1):
        gold_fields = item.get("ground_truth", {})
        resume_ok = True
        for label in LABELS:
            golds = {normalize(g) for g in gold_fields.get(label, []) if normalize(g)}
            if not golds:
                continue
            preds = {normalize(p) for p in pred.get(label, []) if normalize(p)}
            tp, fp, fn, false_preds, missed = score_field(preds, golds, mode)
            for k, v in enumerate((tp, fp, fn)):
                counts[label][k] += v
            if fp or fn:
                resume_ok = False
                errors.append({"resume": i, "field": label, "missed": missed, "wrong": false_preds})
        perfect += resume_ok

    per_label = {label: prf(*counts[label]) for label in LABELS if label in counts}
    tp, fp, fn = (sum(c[k] for c in counts.values()) for k in range(3))
    return {
        "micro": prf(tp, fp, fn),
        "per_label": per_label,
        "resumes_fully_correct": f"{perfect}/{len(test_data)}",
        "errors": errors,
    }


def run_parser(model: str, test_data: list[dict]) -> list[dict]:
    from resumate.extraction.hybrid_parser import BertExtractor, ResumeParser  # noqa: PLC0415

    if not Path(model).exists():
        from huggingface_hub import snapshot_download  # noqa: PLC0415

        model = snapshot_download(model)

    parser = ResumeParser.__new__(ResumeParser)
    parser.bert = BertExtractor(model_path=model)
    if parser.bert.model is None:
        raise SystemExit(f"Could not load model from {model}")
    return [parser.parse(item.get("text") or item.get("content", "")) for item in test_data]


def render(results: dict, model: str, n: int) -> str:
    lines = [
        "# ResuMate evaluation",
        "",
        f"Model: `{model}` · test set: {n} hand-annotated resumes (`data/test/test_resumes.json`).",
        "Generated by `python evaluation/evaluate.py`. False positives are counted.",
        "",
        "## Overall (micro-averaged)",
        "",
        "| Matching | Precision | Recall | F1 | Resumes fully correct |",
        "|---|---|---|---|---|",
    ]
    for mode, r in results.items():
        m = r["micro"]
        lines.append(f"| {mode} | {m['precision']:.1%} | {m['recall']:.1%} | **{m['f1']:.1%}** | "
                     f"{r['resumes_fully_correct']} |")

    lines += ["", "## Per field (lenient matching)", "",
              "| Field | Precision | Recall | F1 | TP | FP | FN |", "|---|---|---|---|---|---|---|"]
    for label, m in results["lenient"]["per_label"].items():
        lines.append(f"| {label} | {m['precision']:.1%} | {m['recall']:.1%} | {m['f1']:.1%} | "
                     f"{m['tp']} | {m['fp']} | {m['fn']} |")

    lines += ["", "## Errors (lenient matching)", "", "| Resume | Field | Missed | Wrong prediction |",
              "|---|---|---|---|"]
    for e in results["lenient"]["errors"]:
        missed = ", ".join(e["missed"]) or "–"
        wrong = ", ".join(w.replace("\n", " ") for w in e["wrong"]) or "–"
        lines.append(f"| {e['resume']} | {e['field']} | {missed} | {wrong} |")
    return "\n".join(lines) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[1])
    ap.add_argument("--model", default=DEFAULT_MODEL, help="Hub model id or local directory")
    args = ap.parse_args()

    test_data = json.loads(TEST_FILE.read_text(encoding="utf-8"))
    predictions = run_parser(args.model, test_data)
    results = {mode: evaluate(predictions, test_data, mode) for mode in ("exact", "lenient")}

    RESULTS_DIR.mkdir(exist_ok=True)
    summary = {"model": args.model, "n_resumes": len(test_data),
               **{mode: {k: v for k, v in r.items() if k != "errors"} for mode, r in results.items()}}
    (RESULTS_DIR / "metrics.json").write_text(json.dumps(summary, indent=2) + "\n", encoding="utf-8")
    (RESULTS_DIR / "report.md").write_text(render(results, args.model, len(test_data)), encoding="utf-8")

    for mode, r in results.items():
        m = r["micro"]
        print(f"{mode:8s} P={m['precision']:.3f} R={m['recall']:.3f} F1={m['f1']:.3f} "
              f"perfect={r['resumes_fully_correct']}")


if __name__ == "__main__":
    main()
